    fun getHizb(hizbNumber: Int): QuranHizb? {
        val safe = hizbNumber.coerceIn(1, 60)
        return ALL_HIZBS.getOrNull(safe - 1)
    }

    /**
     * Finds which Hizb (1..60) contains a given page of the 604-page Mushaf.
     */
    fun getHizbForPage(pageNumber: Int): Int {
        val safePage = pageNumber.coerceIn(1, 604)
        for (i in ALL_HIZBS.indices.reversed()) {
            if (safePage >= ALL_HIZBS[i].startPageNumber) {
                return ALL_HIZBS[i].hizbNumber
            }
        }
        return 1
    }

    /**
     * Finds which Hizb a given verse belongs to.
     */
    fun getHizbForSurahAndVerse(surahId: Int, verseNumber: Int): Int {
        for (i in ALL_HIZBS.indices.reversed()) {
            val h = ALL_HIZBS[i]
            if (surahId > h.startSurahId || (surahId == h.startSurahId && verseNumber >= h.startVerseNumber)) {
                return h.hizbNumber
            }
        }
        return 1
    }
