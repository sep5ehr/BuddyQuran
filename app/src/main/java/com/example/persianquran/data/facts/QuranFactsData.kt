    fun getFactById(id: String): QuranFact? = ALL_FACTS.find { it.id == id }

    fun searchFacts(query: String, category: String): List<QuranFact> {
        val q = query.trim().lowercase()
        return ALL_FACTS.filter { fact ->
            val matchesCategory = (category == "همه" || fact.category == category || fact.type.labelPersian == category)
            val matchesQuery = if (q.isBlank()) true else {
                fact.title.lowercase().contains(q) ||
                fact.summary.lowercase().contains(q) ||
                fact.fullText.lowercase().contains(q) ||
                fact.type.labelPersian.lowercase().contains(q) ||
                fact.category.lowercase().contains(q) ||
                (fact.source != null && fact.source.lowercase().contains(q))
            }
            matchesCategory && matchesQuery
        }
    }
